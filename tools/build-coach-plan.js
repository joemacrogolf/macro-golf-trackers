#!/usr/bin/env node
/* Builds pages/coach-plan.html: the one app page for every plan made in the Plan Builder (www.macro.golf/coach-plan).
   Same engine as the 1-to-1 plans (templates/parts), but the plan isn't known until the player signs in, so every engine
   <script> is written as <script type="text/mg-defer"> (external ones keep their URL in data-src). src/coach-plan.js
   fetches the plan (mg_plan_content), then runs them in order. Rebuild after any change to templates/parts:
     node tools/build-coach-plan.js
   (tools/build-clients.js builds the per-client pages; run both when the engine changes.) */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), parts = path.join(root, 'templates', 'parts');
let tpl = fs.readdirSync(parts).filter(f => f.endsWith('.html')).sort().map(f => fs.readFileSync(path.join(parts, f), 'utf8')).join('');
if (!tpl.includes('/*@@CLIENT@@*/') || !tpl.includes('@@SYNC@@')) throw new Error('template markers missing');
tpl = tpl.replace('/*@@CLIENT@@*/', () => 'var __CP=MGCoachPlan.build();var CLIENT=__CP.CLIENT,SESSIONS=__CP.SESSIONS;')
  .replace('@@SYNC@@', () => 'if(!window.MGCP_PREVIEW)MGSync.init({code:String(window.MGCP_CODE),name:CLIENT.name})');
let n = 0;
tpl = tpl.replace(/<script([^>]*)>([\s\S]*?)<\/script>/g, (m, attrs, body) => {
  n++;
  const src = (attrs.match(/\ssrc="([^"]+)"/) || [])[1];
  return '<script type="text/mg-defer"' + (src ? ' data-src="' + src + '"' : '') + '>' + (src ? '' : body) + '</script>';
});
const head = '<!-- GENERATED by tools/build-coach-plan.js from templates/parts. Do not edit by hand. -->\n' +
  '<script charset="utf-8" src="{{BASE}}src/mg-library.js"></script>\n' +
  '<script charset="utf-8" src="{{BASE}}src/coach-plan.js"></script>\n' +
  '<script charset="utf-8" src="{{BASE}}src/plan-drills.js"></script>\n' +
  '<script>MGCoachPlan.boot()</script>\n';
fs.writeFileSync(path.join(root, 'pages', 'coach-plan.html'), head + tpl);
console.log('built pages/coach-plan.html (' + n + ' engine scripts deferred)');
